-- ============================================================================
-- ClubOn — 성별을 가입 시점에 받습니다
--
-- 매칭은 "원하는 상대의 성별"로 갈리므로, 성별이 없으면 매칭 자체가 서지
-- 않습니다. 그래서 프로필 단계까지 미루지 않고 **가입할 때** 받습니다.
--
-- 진실의 원천은 users.gender 하나입니다. profiles.gender는 매칭·표시에 쓰는
-- 사본이며, 프로필을 저장할 때 users.gender에서 그대로 옮겨 적습니다. 회원이
-- 프로필 화면에서 성별을 바꿔 두 값이 갈라지는 일을 만들지 않기 위해서입니다.
--
-- null이 허용되는 이유는 Google 로그인으로 처음 들어온 회원 때문입니다. 그쪽은
-- 가입 폼을 거치지 않으므로 프로필 단계에서 한 번 물어봅니다.
-- ============================================================================

alter table public.users
  add column if not exists gender public.gender;

comment on column public.users.gender is
  '가입할 때 선언한 성별. 진실의 원천이며 profiles.gender는 여기서 옮겨 적은 사본입니다. Google 가입은 프로필 단계에서 채웁니다.';
